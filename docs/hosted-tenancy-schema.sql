-- Draft empty-database schema spike for hosted Celestin tenancy.
-- Not wired into the SQLite migration runner and not a production migration.
-- Application-generated UUIDs avoid requiring a PostgreSQL extension.

BEGIN;

CREATE TABLE celestin_users (
    id          UUID PRIMARY KEY,
    issuer      TEXT NOT NULL,
    subject     TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (issuer, subject)
);

CREATE TABLE celestin_workspaces (
    id          UUID PRIMARY KEY,
    slug        TEXT NOT NULL UNIQUE,
    name        TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE celestin_workspace_memberships (
    workspace_id UUID NOT NULL REFERENCES celestin_workspaces(id) ON DELETE CASCADE,
    user_id      UUID NOT NULL REFERENCES celestin_users(id) ON DELETE CASCADE,
    role         TEXT NOT NULL CHECK (role IN ('owner', 'admin', 'member')),
    status       TEXT NOT NULL CHECK (status IN ('invited', 'active', 'suspended')),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (workspace_id, user_id)
);

CREATE TABLE celestin_projects (
    id                 UUID PRIMARY KEY,
    workspace_id       UUID NOT NULL REFERENCES celestin_workspaces(id) ON DELETE CASCADE,
    slug               TEXT NOT NULL,
    legacy_project_key TEXT NOT NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (workspace_id, slug),
    UNIQUE (workspace_id, legacy_project_key),
    UNIQUE (workspace_id, id)
);

CREATE TABLE celestin_project_memberships (
    workspace_id UUID NOT NULL,
    project_id   UUID NOT NULL,
    user_id      UUID NOT NULL,
    can_read     BOOLEAN NOT NULL DEFAULT FALSE,
    can_write    BOOLEAN NOT NULL DEFAULT FALSE,
    granted_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (project_id, user_id),
    CHECK (NOT can_write OR can_read),
    FOREIGN KEY (workspace_id, project_id)
        REFERENCES celestin_projects(workspace_id, id) ON DELETE CASCADE,
    FOREIGN KEY (workspace_id, user_id)
        REFERENCES celestin_workspace_memberships(workspace_id, user_id) ON DELETE CASCADE
);

CREATE TABLE celestin_service_identities (
    id          UUID PRIMARY KEY,
    workspace_id UUID NOT NULL REFERENCES celestin_workspaces(id) ON DELETE CASCADE,
    issuer      TEXT NOT NULL,
    subject     TEXT NOT NULL,
    name        TEXT NOT NULL,
    status      TEXT NOT NULL CHECK (status IN ('active', 'revoked')),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (issuer, subject),
    UNIQUE (workspace_id, id)
);

CREATE TABLE celestin_service_project_grants (
    workspace_id       UUID NOT NULL,
    project_id          UUID NOT NULL,
    service_identity_id UUID NOT NULL,
    can_read            BOOLEAN NOT NULL DEFAULT FALSE,
    can_write           BOOLEAN NOT NULL DEFAULT FALSE,
    granted_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (project_id, service_identity_id),
    CHECK (NOT can_write OR can_read),
    FOREIGN KEY (workspace_id, project_id)
        REFERENCES celestin_projects(workspace_id, id) ON DELETE CASCADE,
    FOREIGN KEY (workspace_id, service_identity_id)
        REFERENCES celestin_service_identities(workspace_id, id) ON DELETE CASCADE
);

-- Hosted equivalents. Project-scoped uniqueness permits preserving a local
-- SQLite integer ID in multiple workspaces without making it an authorization key.
CREATE TABLE chat_messages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      UUID NOT NULL REFERENCES celestin_projects(id) ON DELETE CASCADE,
    conversation_id TEXT NOT NULL DEFAULT 'default',
    role            TEXT NOT NULL CHECK (role IN ('user', 'assistant', 'system')),
    content         TEXT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL,
    UNIQUE (project_id, id)
);

CREATE INDEX idx_chat_messages_project_conversation
    ON chat_messages (project_id, conversation_id, id);

CREATE TABLE project_memory (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id        UUID NOT NULL REFERENCES celestin_projects(id) ON DELETE CASCADE,
    key               TEXT NOT NULL,
    value             TEXT NOT NULL,
    status            TEXT NOT NULL CHECK (status IN ('draft', 'approved', 'deprecated')),
    source_message_id  BIGINT,
    created_at         TIMESTAMPTZ NOT NULL,
    updated_at         TIMESTAMPTZ NOT NULL,
    UNIQUE (project_id, key),
    UNIQUE (project_id, id),
    FOREIGN KEY (project_id, source_message_id)
        REFERENCES chat_messages(project_id, id)
        ON DELETE SET NULL (source_message_id)
);

CREATE INDEX idx_project_memory_project ON project_memory (project_id);

COMMIT;
